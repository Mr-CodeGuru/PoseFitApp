#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_font_rendering_into_buffer() {
        let (w, h) = (200, 50);
        let stride_pixels = w;
        let mut buffer = vec![0u8; (w * h * 4) as usize];
        let mut fb = FrameBuffer::new(&mut buffer, w, h, stride_pixels);

        EmbeddedFont::draw_text_rgba(&mut fb, 10, 10, "SQUAT 100%", 2, [255, 255, 255, 255]);

        let non_zero_pixels = fb.buffer.iter().filter(|&&b| b > 0).count();
        assert!(non_zero_pixels > 200);
    }
}
