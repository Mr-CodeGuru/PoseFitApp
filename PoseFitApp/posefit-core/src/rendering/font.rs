#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_font_rendering_into_buffer() {
        let (w, h) = (64, 32);
        let stride = w * 4;
        let mut buffer = vec![0u8; (w * h * 4) as usize];
        let mut fb = FrameBuffer::new(&mut buffer, w, h, stride);

        EmbeddedFont::draw_text_rgba(&mut fb, 4, 4, "A", 1, [255, 255, 255, 255]);

        let non_zero_count = fb.buffer.iter().filter(|&&b| b == 255).count();
        assert!(non_zero_count > 0, "Characters should render into buffer");
    }
}
